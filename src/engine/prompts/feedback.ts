/**
 * 学习者反馈族提示词文本（#237 / ADR-0075 惰性化）：E2「讲给我听」的初学者人设会话包与
 * 定位反馈指令、E1 节级自注反馈指令、回执评审 system 指令的**单源**。
 *
 * **为什么单独落一份**：提示词是长篇散文，写在与它拼装的代码里时散文与代码共用一套语法
 * ——散文里一个反引号或 `${` 就把代码改坏，而 AI 编辑读不出「这里插的是语法还是字面量」。
 * 文本改成惰性串、取值收到 `{{var}}` 占位符表后，散文对代码零语法风险，变量面变成一处
 * 可对账的清单（渲染器见 `../prompt-render.ts`，本模块不含任何插值语法）。
 *
 * **动态材料不进本模块**（ADR-0075 的口径 + 本族的特有危险）：本族提示词的变量面里夹着
 * **学习者自写内容**（自注原文、讲稿 transcript、节正文、回执材料）与**vault 可编辑模板**
 * ——这些值合法地可能带 `{{中文}}`（挖空重述的卡面标记）。它们一律在原落点以朴素拼装注入，
 * **不送进 `render` 的变量面**：把数据送进变量面会把「值里恰好带 `{{英文标识符}}`」这种
 * 真歧义从「原样通过」变成**抛错**，那是行为变更而不是惰性化。本模块只收「写给模型的固定
 * 指令散文」；取值面只有课程名／节点名、回执形态标签、节标题这类**引擎数据**。
 *
 * 本模块不在 `scripts/prompt-bump.mts::TEMPLATE_FILES`（生成模板面）里，故不随版本标记登记；
 * 改这里的文本 = 改生产行为，按 `docs/agents/architecture.md` §8 的收尾登记纪律点名报告。
 */

